// T7.1: traceability table. Lists every acceptance criterion of the P1
// requirements and the test files that name it (e.g. "R5.AC4", "R5.AC4–AC6",
// "R18.AC1, AC6"); a file that names only the requirement counts as
// requirement-level coverage.
// Run: node scripts/traceability.mjs ../labelcraft-specs/specs/0001-browser-label-printer.md > ../labelcraft-specs/specs/0001-traceability.md
import { readFileSync, readdirSync, statSync } from 'node:fs'
import { join, relative, sep } from 'node:path'

const specPath = process.argv[2]
const spec = readFileSync(specPath, 'utf8')

// Requirements and their ACs.
const reqs = []
let current
for (const line of spec.split('\n')) {
  const h = line.match(/^### (R\d+) — (.+?) \[(P\d)\]/)
  if (h) {
    current = { id: h[1], title: h[2], phase: h[3], acs: [] }
    reqs.push(current)
    continue
  }
  if (line.startsWith('## ')) current = undefined
  const ac = current && line.match(/^- AC(\d+): (.*)/)
  if (ac) current.acs.push({ n: Number(ac[1]), text: ac[2] })
}

// Test files.
const files = []
const walk = (dir) => {
  for (const f of readdirSync(dir)) {
    const p = join(dir, f)
    if (statSync(p).isDirectory()) walk(p)
    else if (/\.(test|spec)\.tsx?$/.test(f)) files.push(p)
  }
}
walk('src')
walk('e2e')

const acHits = new Map() // "R5.AC4" -> Set(file)
const reqHits = new Map() // "R5" -> Set(file)
const add = (map, key, file) => {
  if (!map.has(key)) map.set(key, new Set())
  map.get(key).add(file)
}
for (const file of files) {
  const text = readFileSync(file, 'utf8')
  const name = relative('.', file).split(sep).join('/')
  // R5.AC4, R5.AC4–AC6, R18.AC1, AC6, AC8
  for (const m of text.matchAll(
    /\bR(\d+)\.AC(\d+)((?:\s*(?:[–-]|,)\s*AC\d+)*)/g,
  )) {
    const r = m[1]
    let last = Number(m[2])
    add(acHits, `R${r}.AC${last}`, name)
    for (const part of m[3].matchAll(/([–-]|,)\s*AC(\d+)/g)) {
      const n = Number(part[2])
      if (part[1] === ',') add(acHits, `R${r}.AC${n}`, name)
      else for (let k = last + 1; k <= n; k++) add(acHits, `R${r}.AC${k}`, name)
      last = n
    }
  }
  for (const m of text.matchAll(/\bR(\d+)\b(?!\.AC)/g))
    add(reqHits, `R${m[1]}`, name)
}

const p1 = reqs.filter((r) => r.phase === 'P1')
const out = []
let total = 0
let byAc = 0
let byReq = 0
const rows = []
for (const r of p1) {
  for (const ac of r.acs) {
    total++
    const key = `${r.id}.AC${ac.n}`
    const direct = [...(acHits.get(key) ?? [])].sort()
    const req = [...(reqHits.get(r.id) ?? [])].sort()
    let status
    let where
    if (direct.length) {
      byAc++
      status = 'test'
      where = direct.join(', ')
    } else if (req.length) {
      byReq++
      status = 'requirement-level'
      where = req.join(', ')
    } else {
      status = '**manual**'
      where = '—'
    }
    rows.push(`| ${key} | ${status} | ${where} |`)
  }
}
out.push('# 0001 — Traceability (T7.1)')
out.push('')
out.push(
  'Generated by `scripts/traceability.mjs` in the website repo from the P1 acceptance criteria and the test files that name them. "test" = a test names the AC; "requirement-level" = tests name only the requirement; "manual" = covered by the manual checklist (T7.2, T7.3).',
)
out.push('')
out.push(
  `P1 acceptance criteria: ${total}. Named by a test: ${byAc}. Requirement-level: ${byReq}. Manual: ${total - byAc - byReq}.`,
)
out.push('')
out.push('| AC | Coverage | Test files |')
out.push('|----|----------|------------|')
out.push(...rows)
out.push('')
console.log(out.join('\n'))
